export type Option = { id: string; label: string; max_age_months?: number | null };
export type Symptom = Option & {
  zones?: string[];
  general?: boolean;
  min_age_months?: number | null;
  preferred_genders?: CaseData["gender"][];
  onsets?: string[];
  durations?: string[];
  parts?: Record<string, string[]>;
};
export type Question = {
  id: string;
  label: string;
  kind: "single" | "multi";
  options: Option[];
  zones: string[];
  symptoms: string[];
  max_age_months: number | null;
  min_age_months?: number | null;
  genders?: CaseData["gender"][];
  parts?: Record<string, string[]>;
  requires_answers?: Record<string, string[]>;
  answer_or_symptoms?: boolean;
  skip_if_symptoms?: string[];
  skip_if_details?: boolean;
  skip_if_parts?: Record<string, string[]>;
  allow_unspecified_parts?: boolean;
  onsets?: string[];
  durations?: string[];
  evolutions?: string[];
  priority?: number;
  decision_hint?: string;
};
export type BodyDetail = {
  kind: "hand" | "foot" | "arm" | "leg" | "head" | "neck" | "chest" | "abdomen" | "pelvis" | "upper_back" | "lower_back";
  views: ("front" | "back")[];
  default_view: "front" | "back";
  options: (Option & { views: ("front" | "back")[] })[];
};
export type CaseData = {
  age_months: number;
  gender: "female" | "male" | "non_binary" | "other" | "not_specified";
  respondent: "self" | "companion";
  reason: string;
  body_zones: string[];
  body_details: Record<string, string[]>;
  onset: string;
  duration: string;
  evolution: string;
  pain: number | null;
  symptoms: string[];
  alarms: string[];
  answers: Record<string, string | string[]>;
  history: string;
  reviewed: boolean;
};
export type Catalog = {
  version: string;
  specialties: { id: string; name: string; criteria: string }[];
  body_zones: Option[];
  body_details: Record<string, BodyDetail>;
  symptoms: Symptom[];
  alarms: Option[];
  questions: Question[];
  max_followups: number;
};
export type Health = {
  status: "ready" | "model_missing" | "unavailable" | "incompatible";
  model: string;
  message: string;
};
export type NextResult = {
  status: "question" | "complete" | "limit" | "urgent";
  question: Question | null;
  source: "model" | "rules";
  warnings: string[];
  answered: number;
  completion_reason?: "model_enough" | "no_candidates" | "limit" | "urgent" | null;
  candidates_considered?: number;
  eligible_count?: number;
  considered_questions?: { id: string; label: string }[];
};
export type Result = {
  status: "classified" | "inconclusive" | "urgent";
  rankings: { id: string; name: string; probability: number }[];
  warnings: string[];
  model: string;
  catalog_version: string;
  latency_ms: number;
  considered_data: CaseData;
  model_input_exclusions?: string[];
  label: string;
};
